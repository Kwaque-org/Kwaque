seastar::future<codec::result<bytes::fragmented_buffer>>
detail::encode_control_checked(
  const control_data& value,
  control_layout layout,
  codec::cooperative_work& work,
  codec::operation_usage live,
  byte_count parent,
  bytes::allocation_charge_fn charge,
  codec::field_context context) {
    switch (layout.kind) {
    case frame_kind::handshake_request:
        return encode<native::HandshakeRequest>(
          std::get<handshake_request>(value),
          layout,
          work,
          live,
          parent,
          charge,
          context);
    case frame_kind::handshake_response:
        return encode<native::HandshakeResponse>(
          std::get<handshake_response>(value),
          layout,
          work,
          live,
          parent,
          charge,
          context);
    case frame_kind::redirect:
        return encode<native::Redirect>(
          std::get<redirect_control>(value),
          layout,
          work,
          live,
          parent,
          charge,
          context);
    case frame_kind::error:
        return encode<common::Error>(
          std::get<error_control>(value),
          layout,
          work,
          live,
          parent,
          charge,
          context);
    case frame_kind::submitted_batch:
    case frame_kind::assigned_batch:
        break;
    }
    return seastar::make_ready_future<codec::result<bytes::fragmented_buffer>>(
      codec::failure(encode_error(errc::invalid_argument, context)));
}

seastar::future<codec::result<bytes::fragmented_buffer>> encode_control(
  const control& value,
  codec::cooperative_work& work,
  codec::operation_usage other_live,
  byte_count parent,
  bytes::allocation_charge_fn charge,
  codec::field_context context) {
    const auto layout = co_await detail::inspect_control_value(
      value.data(), work, charge, context);
    if (!layout) co_return codec::failure(layout.error());
    if (auto ready = work.poll(encode_error(errc::success, context)); !ready)
        co_return codec::failure(ready.error());
    auto encoded = co_await detail::encode_control_checked(
      value.data(), *layout, work, other_live, parent, charge, context);
    if (!encoded) co_return codec::failure(encoded.error());
    if (auto ready = work.poll(encode_error(errc::success, context)); !ready) {
        co_await work.drain_inline(work.byte_quantum(), work.item_quantum());
        encoded = codec::failure(ready.error());
        co_return codec::failure(ready.error());
    }
    co_return std::move(*encoded);
}
